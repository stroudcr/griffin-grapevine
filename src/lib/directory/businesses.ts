/**
 * Every business in the Local Business Guide.
 *
 * To add a business, add an object to this array;
 * the full shape is `Business` in ./types.ts. A minimal free listing:
 *
 *   {
 *     slug: "business-name",
 *     name: "Business Name",
 *     category: "plumbers",              // a slug from ./categories.ts
 *     tier: "free",                      // or "featured" for paying members
 *     town: "Griffin",
 *     address: griffin("123 Street Name", "30223"),
 *     phone: "(770) 000-0000",
 *     website: "https://example.com",
 *     addedAt: "2026-11-01",
 *   },
 *
 * Featured members can also have tagline, description, services, hours,
 * tags, perk, photos and mentions. Paying members who sign up online live in
 * the database instead and manage their own listings.
 *
 * `npm test` checks the entries (unique slugs, real categories, valid dates
 * and hours) before you deploy.
 *
 * Every entry below was rebuilt on 2026-11-01 from the business's own
 * website, and its comment names the pages used. Hours appear only where the
 * business publishes them; a day left out of `hours` is one the website
 * doesn't list. Where a website doesn't print a street address, the comment
 * says where the address came from.
 *
 * Removed on 2026-11-01 because there was no working website of their own to
 * build a listing from (none found, Facebook only, offline, parked or
 * redirecting elsewhere): Akins Feed & Seed (became Smith Farm Supply in
 * 2020), Angelo's, AComfort, Bank Street Cafe, BenchMark Physical Therapy,
 * Broad Street Mill, Coollectables, Flanders Nurseries, Georgia Real Estate,
 * Gigi's Home and Garden, Griffin Dental Concepts, Griffith's Drive-In,
 * Grubbs Law Firm, Margo's, Nicolas Auto Repair, Oakbridge Insurance,
 * Piedmont Brewery Griffin, Posh Pet Spa, Sweet Southern Salvage, The Auction
 * Block, The Corner Cafe, The Plant Emporium, The Tipsy Daisy and Wilde
 * Roofing. Melvin Rooks & Howell is listed under its current name, Rooks,
 * Waltz, Jackson and Esary.
 */

function griffin(street: string, zip: "30223" | "30224", suite?: string): Business["address"] {
  return suite ? { street, suite, city: "Griffin", state: "GA", zip } : { street, city: "Griffin", state: "GA", zip };
}

function orchardHill(street: string): Business["address"] {
  return { street, city: "Orchard Hill", state: "GA", zip: "30266" };
}

